"""timeline.py: the sound timeline of THIS video and the final mix.

- voice: voice/narration.wav exactly as supplied (read only, never regenerated)
- music bed: audio/music_bed.wav, looped, continuous from 0 to the last frame,
  BED_UNDER_DB below the voice; ducked DUCK_DB under every word of voice/words.json
- SFX: the CUES list below (Cue objects, times in SECONDS)
- master: two-pass loudnorm to -14 LUFS / TP -1 dB -> public/mix.wav
- writes cues.md (GENERATED OUTPUT) and audio/stems/{voice,bed,sfx}.wav
Usage: python tools/timeline.py
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from audio_io import loudness, loudnorm, read_wav, resample, to_stereo, write_wav  # noqa: E402
from sfx import Cue, render  # noqa: E402

SR = 48000
BED_UNDER_DB = 13.0   # bed integrated level below the voice [START]; gate >= 10
DUCK_DB = -3.0        # bed dip under words [C6]
DUCK_RAMP_S = 0.08

story = json.loads(Path("story/story.json").read_text(encoding="utf-8"))
words = json.loads(Path("voice/words.json").read_text(encoding="utf-8"))
DUR = float(story["durationSec"])

# ---- the cues of this video (seconds) ---------------------------------
CUES = [
    Cue(0.0, "whoosh", -16, why="hook: first framing lands"),
]
cue_file = Path("story/cues.json")  # optional per-video list written by the director
if cue_file.exists():
    CUES = [Cue(**c) for c in json.loads(cue_file.read_text(encoding="utf-8"))]

n = int(round(DUR * SR))
voice, vsr = read_wav("voice/narration.wav")
voice = to_stereo(resample(voice, vsr, SR))[:n]
voice = np.pad(voice, ((0, n - len(voice)), (0, 0)))

bed, bsr = read_wav("audio/music_bed.wav")
bed = to_stereo(resample(bed, bsr, SR))
reps = int(np.ceil(n / len(bed)))
bed = np.tile(bed, (reps, 1))[:n]

# duck envelope from the measured words
env = np.ones(n, dtype=np.float32)
duck = 10 ** (DUCK_DB / 20)
for w in words:
    a, b = int(max(0, w["s"] - DUCK_RAMP_S) * SR), int(min(DUR, w["e"] + DUCK_RAMP_S) * SR)
    env[a:b] = duck
k = int(DUCK_RAMP_S * SR)
env = np.convolve(env, np.ones(k) / k, mode="same").astype(np.float32)

Path("audio/stems").mkdir(parents=True, exist_ok=True)
write_wav("audio/stems/voice.wav", voice, SR)
write_wav("audio/stems/_bed_raw.wav", bed, SR)
lv, _ = loudness("audio/stems/voice.wav")
lb, _ = loudness("audio/stems/_bed_raw.wav")
bed = bed * (10 ** ((lv - BED_UNDER_DB - lb) / 20)) * env[:, None]
fade = int(0.12 * SR)
bed[-fade:] *= np.linspace(1, 0.35, fade)[:, None]  # short tail, never silence
write_wav("audio/stems/bed.wav", bed, SR)

sfx = np.zeros_like(voice)
for c in CUES:
    x = render(c, SR)
    a = int(c.t * SR)
    m = min(len(x), n - a)
    if m > 0:
        sfx[a:a + m] += x[:m]
write_wav("audio/stems/sfx.wav", sfx, SR)

mix = voice + bed + sfx
Path("public").mkdir(exist_ok=True)
write_wav("audio/_premaster.wav", mix * 0.5, SR)
loudnorm("audio/_premaster.wav", "public/mix.wav")
I, TP = loudness("public/mix.wav")

lines = ["# cues.md - GENERATED by tools/timeline.py. Do not edit; edit the Cue list.", "",
         f"voice {lv:.1f} LUFS | bed {lv - BED_UNDER_DB:.1f} LUFS (under by {BED_UNDER_DB} dB) | duck {DUCK_DB} dB under {len(words)} words",
         f"master: {I:.2f} LUFS, TP {TP:.2f} dBTP", "", "| t (s) | sound | gain dB | lands on |", "|---|---|---|---|"]
lines += [f"| {c.t:.2f} | {c.name}{' (' + c.file + ')' if c.file else ' (synth)'} | {c.gain_db} | {c.why} |" for c in CUES]
Path("cues.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[2:4]))
