"""sfx.py: the Cue object and the sound makers.

Cue times are in SECONDS (never frames). A cue plays a supplied sample
(file=...) or, only when no sample fits, a small synthetic sound below.
cues.md is GENERATED by timeline.py from these objects; never edit it.
"""
from dataclasses import dataclass
from typing import Optional

import numpy as np

from audio_io import read_wav, resample, to_stereo


@dataclass
class Cue:
    t: float                    # seconds from the start of the video
    name: str                   # what the sound is (plain words)
    gain_db: float = -12.0
    file: Optional[str] = None  # a supplied sample; preferred over synth
    why: str = ""               # the on-screen action it lands on


def _env(n, sr, a=0.005, r=0.25):
    t = np.arange(n) / sr
    return np.minimum(1, t / a) * np.exp(-t / r)


def synth(name, sr, seed=1):
    rng = np.random.default_rng(seed)
    if name == "whoosh":
        n = int(0.45 * sr); x = rng.standard_normal(n)
        k = np.linspace(0.02, 0.35, n); y = np.zeros(n)
        for i in range(1, n):
            y[i] = y[i - 1] + k[i] * (x[i] - y[i - 1])
        return y * np.sin(np.linspace(0, np.pi, n)) * 0.6
    if name == "thud":
        n = int(0.35 * sr); t = np.arange(n) / sr
        return np.sin(2 * np.pi * (70 - 40 * t) * t) * _env(n, sr, 0.002, 0.09)
    if name == "chime":
        n = int(1.2 * sr); t = np.arange(n) / sr
        return sum(np.sin(2 * np.pi * f * t) / (i + 1) for i, f in enumerate([880, 1320, 1760])) * _env(n, sr, 0.003, 0.4) * 0.5
    if name == "crackle":
        n = int(1.0 * sr); y = np.zeros(n)
        for p in rng.integers(0, n - 200, 40):
            y[p:p + 200] += rng.standard_normal(200) * np.exp(-np.arange(200) / 30) * rng.uniform(0.2, 1)
        return y * 0.4
    if name == "laugh":
        n = int(0.9 * sr); t = np.arange(n) / sr
        return np.sin(2 * np.pi * 220 * t) * (0.5 + 0.5 * np.sign(np.sin(2 * np.pi * 6 * t))) * _env(n, sr, 0.01, 0.5) * 0.3
    raise ValueError(f"no synth for {name}; supply a sample file")


def render(cue: Cue, sr):
    if cue.file:
        x, s = read_wav(cue.file)
        x = to_stereo(resample(x, s, sr))
    else:
        x = to_stereo(synth(cue.name, sr, seed=int(cue.t * 1000))[:, None].astype(np.float32))
    return x * (10 ** (cue.gain_db / 20))
